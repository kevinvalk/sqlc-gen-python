"""The type-truth probe: each mapped type of each engine, at its edges, per
driver.

Each engine's part says how it reads its types (``typemap_postgres.py``,
``typemap_mysql.py``, ``typemap_sqlite.py``); what they hold in common is what
makes a type's annotation true: every edge a database can hold of it comes
back, through every driver, as a value of exactly that annotation, or the
driver raises. A value outside it is a **mismatch**, and fails
``cargo xtask verify``.

The result is ``docs/typemap.md``.
"""

from __future__ import annotations

import re
import sys
import typing
from typing import TYPE_CHECKING, Any

import mysql
import postgres
import typemap_mysql
import typemap_postgres
import typemap_sqlite
from typemap_probe import versions

if TYPE_CHECKING:
    import sqlalchemy

    from typemap_probe import Section


def probe(postgresql: sqlalchemy.URL, mysql_server: sqlalchemy.URL) -> list[Section]:
    """Probe every engine: PostgreSQL and MySQL on their servers, SQLite in
    memory.
    """
    return [
        typemap_postgres.probe(postgresql),
        typemap_mysql.probe(mysql_server),
        typemap_sqlite.probe(),
    ]


def render(sections: list[Section], newer: str) -> str:
    """``docs/typemap.md``; ``newer`` says what else ``verify`` held the
    annotations to.
    """
    python = ".".join(map(str, sys.version_info[:2]))
    lines = [
        "# Types at runtime",
        "",
        "Generated by `cargo xtask verify` (`tests/python/typemap.py`); do not edit.",
        (
            f"Observed with {versions('sqlalchemy')} on Python {python}; `verify`"
            f" holds every annotation on {newer} too."
        ),
        "",
        (
            "Each type in the generator's maps, with the annotation the generator"
            " writes for it, and the Python types each driver returned for NULL and"
            " the edge values of the probe. A **mismatch** (a value outside the"
            " annotation) fails `verify`. A driver that raises on an edge, or returns"
            " a value that does not bind back to the one it read (**lossy**), is"
            " listed under the table: these are properties of the databases and"
            " their drivers, which the annotation cannot express."
        ),
    ]
    for section in sections:
        lines += [
            "",
            f"## {section.engine}",
            "",
            f"Observed on {section.observed}.",
            "",
            _row(section.engine, "Annotation", *section.drivers, "Verdict"),
            "|" + "---|" * (len(section.drivers) + 3),
        ]
        for p in section.probes:
            seen = [
                " ".join(f"`{t}`" for t in sorted(p.seen.get(d, ()))) or "-"
                for d in section.drivers
            ]
            verdict = "**MISMATCH**" if p.mismatches else "ok"
            lines.append(
                _row(f"`{p.type}`", f"`{_annotation(p.annotation)}`", *seen, verdict)
            )
        lines += [
            "",
            f"### {section.engine} edges that raise or are lossy",
            "",
            _row(section.engine, "Edge", *section.drivers),
            "|" + "---|" * (len(section.drivers) + 2),
        ]
        for p in section.probes:
            for edge, by_driver in p.notes.items():
                notes = [by_driver.get(d, "") for d in section.drivers]
                lines.append(_row(f"`{p.type}`", f"`{_code(edge)}`", *notes))
    return "\n".join(lines) + "\n"


def _row(*cells: str) -> str:
    """A table row; a `|` in a cell, even in code, must be escaped."""
    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


def _code(edge: str, width: int = 120) -> str:
    """An edge as one line of code, cut where it is a long literal."""
    return edge if len(edge) <= width else edge[: width - 3] + "..."


def _annotation(hint: Any) -> str:  # noqa: ANN401
    if isinstance(hint, type) and not typing.get_args(hint):
        return hint.__name__
    return re.sub(r"\b(?:[a-z_]+\.)+", "", str(hint)).replace("NoneType", "None")


def main() -> int:
    """``typemap.py ROOT``: probe the golden cases at ``ROOT``; 1 on any
    mismatch.
    """
    sys.path.insert(0, sys.argv[1])
    with postgres.server() as postgresql, mysql.server() as mysql_server:
        sections = probe(postgresql, mysql_server)
    mismatches = [m for section in sections for m in section.mismatches]
    print(*mismatches, sep="\n")
    return int(bool(mismatches))


if __name__ == "__main__":
    sys.exit(main())
