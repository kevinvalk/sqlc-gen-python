"""The type-truth probe, which writes ``docs/typemap.md``: each mapped type of each engine, at its edges, per driver.

usage: typemap.py ROOT

A type's annotation is true when every edge a database can hold of it comes back, through every driver, as a value of
exactly that annotation, or the driver raises. A value outside it is a **mismatch** and fails ``cargo xtask verify``.
Each engine's part (``typemap_postgres.py``, ``typemap_psycopg.py``, ``typemap_mysql.py``, ``typemap_sqlite.py``) says
how it reads its types.
"""

from __future__ import annotations

import re
import sys
import typing
from typing import TYPE_CHECKING, Any

import mysql
import postgres
import typemap_mysql
import typemap_postgres
import typemap_psycopg
import typemap_sqlite
from typemap_probe import cut, versions

if TYPE_CHECKING:
    import sqlalchemy

    from typemap_probe import Section


def probe(postgresql: sqlalchemy.URL, mysql_server: sqlalchemy.URL) -> list[Section]:
    return [
        typemap_postgres.probe(postgresql),
        typemap_psycopg.probe(postgresql),
        typemap_mysql.probe(mysql_server),
        typemap_sqlite.probe(),
    ]


def render(sections: list[Section], newer: str) -> str:
    """Render ``docs/typemap.md``, where ``newer`` says what else ``verify`` held the annotations to."""
    python = ".".join(map(str, sys.version_info[:2]))
    lines = [
        "# Types at runtime",
        "",
        "Generated by `cargo xtask verify` (`tests/python/typemap.py`); do not edit.",
        (f"Observed with {versions('sqlalchemy')} on Python {python}; `verify` holds every annotation on {newer} too."),
        "",
        (
            "Each type in the generator's maps, with the annotation the generator"
            " writes for it, and the Python types each driver returned for NULL and"
            " the edge values of the probe. A **mismatch** (a value outside the"
            " annotation) fails `verify`. A driver that raises on an edge, or returns"
            " a value that does not bind back to the one it read (**lossy**), is"
            " listed under the table: these are properties of the databases and"
            " their drivers, which the annotation cannot express."
        ),
    ]
    for section in sections:
        lines += [
            "",
            f"## {section.engine}",
            "",
            f"Observed on {section.observed}.",
            "",
            _row(section.engine, "Annotation", *section.drivers, "Verdict"),
            "|" + "---|" * (len(section.drivers) + 3),
        ]
        for probe in section.probes:
            seen = [" ".join(f"`{t}`" for t in sorted(probe.seen.get(d, ()))) or "-" for d in section.drivers]
            verdict = "**MISMATCH**" if len(probe.mismatches) > 0 else "ok"
            lines.append(_row(f"`{probe.type}`", f"`{_annotation(probe.annotation)}`", *seen, verdict))
        lines += [
            "",
            f"### {section.engine} edges that raise or are lossy",
            "",
            _row(section.engine, "Edge", *section.drivers),
            "|" + "---|" * (len(section.drivers) + 2),
        ]
        for probe in section.probes:
            for edge, by_driver in probe.notes.items():
                notes = [by_driver.get(d, "") for d in section.drivers]
                lines.append(_row(f"`{probe.type}`", f"`{cut(edge, 120)}`", *notes))
    return "\n".join(lines) + "\n"


def _row(*cells: str) -> str:
    # A `|` in a cell must be escaped, even inside code.
    return "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"


def _annotation(hint: Any) -> str:
    if isinstance(hint, type) and len(typing.get_args(hint)) <= 0:
        return hint.__name__
    return re.sub(r"\b(?:[a-z_]+\.)+", "", str(hint)).replace("NoneType", "None")


def main() -> int:
    sys.path.insert(0, sys.argv[1])
    with postgres.server() as postgresql, mysql.server() as mysql_server:
        sections = probe(postgresql, mysql_server)
    mismatches = [mismatch for section in sections for mismatch in section.mismatches]
    print(*mismatches, sep="\n")
    return 1 if len(mismatches) > 0 else 0


if __name__ == "__main__":
    sys.exit(main())
