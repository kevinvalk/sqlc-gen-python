pub fn files(api: &Api, config: &Config, sqlc_version: &str) -> Vec<plugin::File> {
    let header = header(sqlc_version, config);
    let modules = config.modules();
    let file = |name: String, body: &[ast::Stmt]| {
        let exempt = match python::trips_s105(body) {
            true => "# ruff: noqa: S105\n",
            false => "",
        };
        let contents = header.clone() + exempt + &python::render(body, &modules, config.models.module.as_deref());
        plugin::File {
            name,
            contents: contents.into_bytes(),
        }
    };
    // We write only our own modules into `out`, which may well be a package of the application's (a component's
    // `queries.py` beside its `logic.py`), so `__init__.py` is the application's to write, and so is a `py.typed`.
    let errors = match config.backend.defines_errors() {
        true => errors(),
        false => Vec::new(),
    };
    let models = (config.models.module.is_none()).then(|| {
        file(
            "models.py".into(),
            &[errors, models::module(api, config.records)].concat(),
        )
    });
    let queries =
        (api.modules.iter()).map(|module| file(format!("{}.py", module.name), &queries::module(module, config)));
    models.into_iter().chain(queries).collect()
}

/// We prepend the header as text, as ruff's AST has nowhere to put a `#` comment. sqlc's version makes a regenerated
/// file's diff explain itself. The plugin's own is the tag in the user's `sqlc.yaml`, as in sqlc's own plugins, so a
/// new release does not rewrite every file.
///
/// IMPORTANT: sqlc's version is the only text of the request we write outside the tree, and anything but one printable
/// word could end the comment and be code. So we leave anything else out, as we do an unknown version.
fn header(sqlc_version: &str, config: &Config) -> String {
    let is_word = !sqlc_version.is_empty() && sqlc_version.chars().all(|c| c.is_ascii_graphic());
    let versions = match is_word && !config.omit_sqlc_version {
        true => format!("# versions:\n#   sqlc {sqlc_version}\n"),
        false => String::new(),
    };
    format!(
        "# Code generated by {}. DO NOT EDIT.\n{versions}",
        env!("CARGO_PKG_NAME")
    )
}

/// For a backend whose library has no errors for a `:one` without exactly one row. They live with the models, the one
/// module every query module reads.
fn errors() -> Vec<ast::Stmt> {
    [
        (NO_ROW_ERROR, "A `:one` query returned no row."),
        (MULTIPLE_ROWS_ERROR, "A `:one` query returned more than one row."),
    ]
    .into_iter()
    .map(|(error, doc)| class(error, [], [LOOKUP_ERROR.into()], [docstring(doc)]))
    .collect()
}

struct Attribute {
    name: String,
    annotation: ast::Expr,
    comment: String,
    /// How `from_row` reads it from `row`, for a record built from results.
    read: Option<ast::Expr>,
    default: Option<ast::Expr>,
}

impl Attribute {
    fn column(field: &Field, index: usize, scope: Scope) -> Self {
        Self {
            name: field.name.clone(),
            annotation: field.ty.annotation(scope),
            comment: String::new(),
            read: Some(field.ty.read(ROW.index(int(index)), scope)),
            default: None,
        }
    }
}

/// A record is frozen so rows are values, rejects a misspelt attribute (a dataclass by its slots, a pydantic model by
/// forbidding extra fields), and is keyword-only so construction cannot depend on column order. A record of results
/// builds itself from a driver's row by position, so duplicate column names cannot confuse it.
fn record(class_name: &str, comment: &str, attributes: &[Attribute], records: Records) -> ast::Stmt {
    let fields = (attributes.iter()).flat_map(|attribute| {
        let declaration = match &attribute.default {
            Some(default) => ann_assign(&attribute.name, attribute.annotation.clone(), default.clone()),
            None => annotate(&attribute.name, attribute.annotation.clone()),
        };
        std::iter::once(declaration).chain(documentation(&attribute.comment))
    });
    let reads: Option<Vec<ast::Keyword>> = (attributes.iter())
        .map(|attribute| Some(keyword(&attribute.name, attribute.read.clone()?)))
        .collect();
    let from_row = reads.filter(|reads| !reads.is_empty()).map(|reads| {
        Function {
            decorators: vec![CLASSMETHOD.into()],
            parameters: vec![receiver(CLS), parameter(ROW, SEQUENCE.index(ANY))],
            body: vec![return_(CLS.call_with([], reads))],
            ..Function::new(FROM_ROW, forward(name(class_name)))
        }
        .into()
    });
    // A misspelt field of a `**` dict is an error to pydantic, as it is to a dataclass, and an override's type or a
    // library's (a psycopg `Range`) is checked as an instance of its class. We protect no namespace, as pydantic warns
    // of a field that only starts as one of its methods (`model_dump_at`), and a field is never named as one
    // (`PYDANTIC_MODEL` in `api/names.rs`).
    let config = (records == Records::Pydantic).then(|| {
        let options = [
            keyword("frozen", true_()),
            keyword("extra", string("forbid")),
            keyword("arbitrary_types_allowed", true_()),
            keyword("protected_namespaces", tuple(vec![])),
        ];
        assign(MODEL_CONFIG, PYDANTIC.attr("ConfigDict").call_with([], options))
    });
    let body = (documentation(comment).into_iter())
        .chain(config)
        .chain(fields)
        .chain(from_row);
    match records {
        Records::Dataclass => {
            let options = ["frozen", "slots", "kw_only"].map(|option| keyword(option, true_()));
            class(
                class_name,
                [DATACLASSES.attr("dataclass").call_with([], options)],
                [],
                body,
            )
        }
        Records::Pydantic => class(class_name, [], [PYDANTIC.attr("BaseModel")], body),
    }
}

fn documentation(comment: &str) -> Option<ast::Stmt> {
    (!comment.trim().is_empty()).then(|| docstring(comment.trim()))
}
