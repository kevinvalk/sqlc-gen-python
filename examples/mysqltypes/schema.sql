-- A column of every type the plugin maps on MySQL, each nullable: the runtime
-- proof (tests/python/typemap.py) stores each edge of a type in its column,
-- alone in its row, and reads it back through every driver.
CREATE TABLE scalars (
  c_bool BOOL,
  c_tinyint TINYINT,
  c_tinyint_unsigned TINYINT UNSIGNED,
  c_smallint SMALLINT,
  c_smallint_unsigned SMALLINT UNSIGNED,
  c_mediumint MEDIUMINT,
  c_mediumint_unsigned MEDIUMINT UNSIGNED,
  c_int INT,
  c_int_unsigned INT UNSIGNED,
  c_bigint BIGINT,
  c_bigint_unsigned BIGINT UNSIGNED,
  c_year YEAR,
  c_float FLOAT,
  c_double DOUBLE,
  c_decimal DECIMAL(65, 30),
  c_char CHAR(3),
  c_varchar VARCHAR(20),
  c_tinytext TINYTEXT,
  c_text TEXT,
  c_mediumtext MEDIUMTEXT,
  c_longtext LONGTEXT,
  c_json JSON,
  c_binary BINARY(3),
  c_varbinary VARBINARY(20),
  c_tinyblob TINYBLOB,
  c_blob BLOB,
  c_mediumblob MEDIUMBLOB,
  c_longblob LONGBLOB,
  c_bit_1 BIT(1),
  c_bit_64 BIT(64),
  c_date DATE,
  c_datetime DATETIME(6),
  c_timestamp TIMESTAMP(6) NULL,
  c_time TIME(6),
  c_set SET('read', 'write', 'é')
);
